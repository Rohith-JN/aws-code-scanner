#!/usr/bin/env python3
"""Embed scanner files in a buildspec for projects using NO_SOURCE/inline YAML."""

from pathlib import Path
import shlex
import sys

from scanner_source import SCANNER_FILES


def generate(repo):
    base = (repo / "buildspec.yml").read_text(encoding="utf-8")
    install = "      - bash scripts/install-scanners.sh .scanner-tools"
    if base.count(install) != 1:
        raise ValueError("Expected exactly one scanner installation command")
    bootstrap = [
        "set -euo pipefail",
        "# Materialize trusted scanner files in the initially empty source directory.",
        "mkdir -p scripts config codeql",
    ]
    for index, filename in enumerate(SCANNER_FILES):
        content = (repo / filename).read_text(encoding="utf-8")
        delimiter = f"SCANNER_FILE_{index}_END"
        if delimiter in content.splitlines():
            raise ValueError(f"Heredoc delimiter occurs in {filename}")
        bootstrap.append(f"cat > {shlex.quote(filename)} <<'{delimiter}'")
        bootstrap.extend(content.splitlines())
        bootstrap.append(delimiter)
    bootstrap.append("bash scripts/install-scanners.sh .scanner-tools")
    block = "      - |\n" + "\n".join("        " + line if line else "" for line in bootstrap)
    header = (
        "# Generated by scripts/generate-inline-buildspec.py; edit the source files and regenerate.\n"
        "# Paste this ENTIRE file into CodeBuild's inline buildspec editor. No source ZIP is required.\n"
    )
    return header + base.replace(install, block)


def main():
    if len(sys.argv) != 2:
        sys.exit("Usage: generate-inline-buildspec.py OUTPUT.yml")
    repo = Path(__file__).resolve().parent.parent
    output = Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    # Regeneration deliberately updates this derived artifact in place.
    with output.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(generate(repo))
    print(output.resolve())


if __name__ == "__main__":
    main()
